const stepsByKey = new Map<string, TemplateStep>(TEMPLATE_STEPS.map((step) => [step.key, step]));

export function isStepKey(value: string): value is StepKey {
  return stepsByKey.has(value);
}

export function templateStep(key: StepKey): TemplateStep {
  const step = stepsByKey.get(key);
  if (!step) throw new Error(`Unknown step key: ${key}`);
  return step;
}
