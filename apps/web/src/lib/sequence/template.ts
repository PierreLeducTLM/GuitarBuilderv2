/** Stable identifier of a template step, used to store its state. */
export type StepKey = (typeof STEP_KEYS)[number];

/** Construction-variant highlight of a step (Variant Step Highlighting). */
export type StepHighlight = "variant" | "bridgeBlank";

export interface TemplateStep {
  key: StepKey;
  /** Template position, 1-132 (Step Numbers). */
  number: number;
  /** Template group, 1-15. Groups organize the template but are not displayed. */
  group: number;
  /** The only guitar type the step applies to, or null when it applies to both. */
  guitarType: GuitarType | null;
  /** Whether the step applies only to builds with a BOBO neck. */
  needsBobo: boolean;
  highlight: StepHighlight | null;
}

